"""Stopword classification for concept extraction.

Stopword lists target tokens that appear in code or comments with extremely
high frequency and contribute no semantic signal to concept ranking. They are
NOT removed from the concept graph — they continue to receive REFERENCES and
IS_NAMED_IN edges (so queries can still find them as nodes). They are excluded
from CO_OCCURS_WITH (by the extractor) and from centrality computation (by the
retrieval layer). Conservative on English (avoid losing meaningful nouns/verbs);
aggressive on language keywords (always syntactic).

``classify()`` returns a ``StopwordClass``; callers decide how to apply it.
English and code stop-lists are global; per-language lists add keyword noise
from each grammar.
"""

