_lock = threading.Lock()
_english_extensions: set[str] = set()
_code_extensions: set[str] = set()
_language_extensions: dict[str, set[str]] = {}


def classify(token: str, *, language: str | None = None) -> StopwordClass:
    """Classify *token* for centrality penalty — never implies hard drop."""
    normalized = token.lower()
    with _lock:
        if normalized in ENGLISH_STOPWORDS or normalized in _english_extensions:
            return StopwordClass.ENGLISH
        if normalized in CODE_STOPWORDS or normalized in _code_extensions:
            return StopwordClass.CODE
        if language is not None:
            lang_key = language.lower()
            lang_set = LANGUAGE_STOPWORDS.get(lang_key, frozenset())
            lang_ext = _language_extensions.get(lang_key, set())
            if normalized in lang_set or normalized in lang_ext:
                return StopwordClass.LANGUAGE
    return StopwordClass.NOT_STOPWORD


def is_stopword(token: str, *, language: str | None = None) -> bool:
    """Return True when *token* matches any stopword category."""
    return classify(token, language=language) != StopwordClass.NOT_STOPWORD


def extend_stopwords(
    *,
    english: Iterable[str] = (),
    code: Iterable[str] = (),
    language: dict[str, Iterable[str]] | None = None,
) -> None:
    """Add project- or test-specific stopwords in a thread-safe way."""
    with _lock:
        _english_extensions.update(word.lower() for word in english)
        _code_extensions.update(word.lower() for word in code)
        if language:
            for lang, words in language.items():
                lang_key = lang.lower()
                bucket = _language_extensions.setdefault(lang_key, set())
                bucket.update(word.lower() for word in words)
